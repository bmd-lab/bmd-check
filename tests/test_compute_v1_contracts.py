def no_scheduler(command, **kwargs):
    return subprocess.CompletedProcess(command, 0, stdout="", stderr="")


def inspect_v1_run(runtime_payload: bytes | None):
    submission = desired_output_submission()
    run_dir = submission["paths"]["run_dir"]
    files = {f"{run_dir}/submission.json": json.dumps(submission).encode("utf-8")}
    if runtime_payload is not None:
        files[submission["paths"]["runtime_environment"]] = runtime_payload
    remote = ri.RemoteFixture(files=files, directories={run_dir})
    return inspect_remote_run(
        ri.cluster(),
        run_dir,
        remote_runner=remote,
        slurm_runner=no_scheduler,
        derive_scientific=False,
    )


