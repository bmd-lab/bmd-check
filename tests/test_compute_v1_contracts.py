def test_current_compute_capability_payload_parses_with_all_eight_capabilities():
    capabilities = parse_capability_payload(json.dumps(capabilities_payload()))

    assert capabilities.source["commit"] == COMPUTE_V1_COMMIT
    assert capabilities.source["dirty"] is False
    pairs = set(supported_capability_pairs(capabilities))
    assert len(pairs) == 8
    assert ("dos", "hse06") in pairs
    assert pairs == {
        (stage, theory)
        for stage in ("relax", "static", "dos", "band_structure")
        for theory in ("pbe", "hse06")
    }


def test_stage_modifier_support_is_preserved_verbatim():
    payload = capabilities_payload()
    capabilities = parse_capability_payload(json.dumps(payload))

    assert capabilities.stage_modifier_support == tuple(payload["stage_modifier_support"])
    for record in payload["stage_modifier_support"]:
        declared = supported_modifier_combinations(
            capabilities,
            record["stage_type"],
            record["theory"],
        )
        assert declared == tuple(
            frozenset(combination) for combination in record["supported_modifier_combinations"]
        )


def test_representative_allowed_and_forbidden_stage_modifiers_come_from_compute():
    capabilities = parse_capability_payload(json.dumps(capabilities_payload()))

    pbe_dos = supported_modifier_combinations(capabilities, "dos", "pbe")
    pbe_static = supported_modifier_combinations(capabilities, "static", "pbe")
    hse_static = supported_modifier_combinations(capabilities, "static", "hse06")
    pbe_relax = supported_modifier_combinations(capabilities, "relax", "pbe")

    assert frozenset({"dft_u", "spin_polarized"}) in pbe_dos
    assert all("soc" not in combination for combination in pbe_dos)
    assert frozenset({"soc"}) in pbe_static
    assert frozenset({"soc"}) in hse_static
    assert frozenset({"dispersion"}) not in hse_static
    assert all("soc" not in combination for combination in pbe_relax)


def test_historical_capability_payload_without_modifier_support_still_parses():
    capabilities = parse_capability_payload(json.dumps(test_compute.schema_v1_payload()))

    assert capabilities.stage_modifier_support is None
    # Not declared means unknown, never "no modifiers".
    assert supported_modifier_combinations(capabilities, "static", "pbe") is None


def test_modifier_support_is_not_inferred_from_broad_treatment_descriptions():
    payload = capabilities_payload()
    soc_policy = next(
        item
        for item in payload["automatic_default_treatments"]["treatments"]
        if item["modifier"] == "soc"
    )
    # The policy prose says SOC applies to "every non-relaxation stage" ...
    assert "non-relaxation" in soc_policy["application"]
    capabilities = parse_capability_payload(json.dumps(payload))
    # ... but only stage_modifier_support decides; Compute rejects SOC on PBE DOS.
    assert all("soc" not in combination for combination in supported_modifier_combinations(capabilities, "dos", "pbe"))

    historical = deepcopy(payload)
    historical.pop("stage_modifier_support")
    historical_capabilities = parse_capability_payload(json.dumps(historical))
    # With no declared support, Agent reports nothing rather than reading the policy text.
    assert supported_modifier_combinations(historical_capabilities, "dos", "pbe") is None


